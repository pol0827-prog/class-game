// 문장에서 키워드를 찾아 등장 순서대로 이모지 만들기
export function emojify(text, max = 5) {
  const t = String(text || '');
  const hits = [];
  for (const [k, e] of DICT) {
    const i = t.indexOf(k);
    if (i >= 0) hits.push({ i, e, len: k.length });
  }
  hits.sort((a, b) => a.i - b.i || b.len - a.len);
  const out = [];
  for (const h of hits) { if (!out.includes(h.e)) out.push(h.e); if (out.length >= max) break; }
  return out.length ? out.join('') : '❓✨';
}

// 미스터리 키워드: 설명을 잘라 힌트 5개 만들기 (어려움 → 쉬움)
export function localKeywordHints(concept, content) {
  const name = String(concept).replace(/\s*\(.*?\)\s*/g, '').trim();
  const parts = maskWord(content, concept)
    .split(/(?<=[.!?。])\s+|\n+|\s*[;·/]\s*|,\s+/)
    .map(s => s.trim().replace(/[.。]$/, '')).filter(s => s.length >= 2).slice(0, 3);
  const fill = [`${[...name.replace(/\s/g, '')].length}글자`, `첫 글자는 '${[...name][0] || ''}'`];
  const hints = [...parts];
  for (const f of fill) if (hints.length < 4) hints.push(f);
  hints.push(`초성: ${chosung(name)}`);
  while (hints.length < 5) hints.unshift('오늘 수업에 나오는 개념이에요');
  return hints.slice(0, 5);
}

// 줄 단위 "개념 | 설명" 읽기
export function readPairs(text) {
  return String(text || '').split('\n').map(l => l.trim()).filter(l => l && !l.startsWith('#')).map(l => {
    const i = l.indexOf('|');
    return i < 0 ? { a: l.trim(), b: '' } : { a: l.slice(0, i).trim(), b: l.slice(i + 1).replace(/\|/g, ',').trim() };
  }).filter(p => p.a);
}
