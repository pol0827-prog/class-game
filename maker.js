const CHO = 'ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ';

export function chosung(text) {
  return [...String(text || '')].map(ch => {
    const c = ch.charCodeAt(0) - 0xAC00;
    return c >= 0 && c <= 11171 ? CHO[Math.floor(c / 588)] : ch;
  }).join('');
}

// 설명 속 정답 단어를 ○○로 가리기 (조사 붙은 경우 포함)
export function maskWord(text, word) {
  let out = String(text || '');
  const w = String(word || '').replace(/\s*\(.*?\)\s*/g, '').trim();
  if (!w) return out;
  const parts = [w, w.replace(/\s+/g, '')];
  for (const p of parts) if (p) out = out.split(p).join('○'.repeat(Math.min(4, [...p].length)));
  return out;
}

