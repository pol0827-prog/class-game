// 문자열(여러 줄) → 문제 배열
export function parseLines(format, text) {
  const out = [];
  for (const raw of String(text || '').split('\n')) {
    const line = raw.trim();
    if (!line || line.startsWith('#')) continue;
    const c = line.split('|').map(s => s.trim());
    switch (format) {
      case 'emoji':    out.push({ q: c[0], a: c[1] || '', hint: c[2] || '' }); break;
      case 'chosung':  out.push({ q: c[0], a: c[1] || '', hint: c[2] || '' }); break;
      case 'keyword':  out.push({ a: c[0], hints: c.slice(1, 6).filter(Boolean) }); break;
      case 'qa':       out.push({ q: c[0], a: c[1] || '' }); break;
      case 'balance':  out.push({ a: c[0], b: c[1] || '' }); break;
      case 'poll': {
        const opts = (c[1] || 'O / X').split('/').map(s => s.trim()).filter(Boolean);
        const ans = (c[2] || '').trim();
        out.push({ q: c[0], options: opts, answer: ans ? opts.indexOf(ans) : -1 }); break;
      }
      case 'fermi':    out.push({ q: c[0], a: c[1] || '' }); break;
      case 'question': out.push({ q: c[0] }); break;
      case 'check':    out.push({ q: c[0] }); break;
      case 'truths':   out.push({ s: c.slice(0, 3), lie: Math.max(0, Math.min(2, (parseInt(c[3], 10) || 1) - 1)) }); break;
      case 'ox':       out.push({ q: c[0], a: (c[1] || 'O').toUpperCase().startsWith('X') ? 'X' : 'O', note: c[2] || '' }); break;
      case 'song':     out.push({ a: c[0], hint: c[1] || '' }); break;
      case 'concept':  out.push({ q: c[0], a: c[1] || '' }); break;
      case 'liar':     out.push({ cat: c[0], words: (c[1] || '').split(',').map(s => s.trim()).filter(Boolean) }); break;
      case 'kword':    out.push({ a: c[0], hint: c[1] || '' }); break;
      default:         out.push({ q: c[0], a: c[1] || '' });
    }
  }
  return out;
}

// AI 결과(객체 배열) → 편집용 문자열
export function itemsToLines(format, items) {
  return (items || []).map(it => {
    switch (format) {
      case 'keyword': return [it.answer, ...(it.hints || [])].join(' | ');
      case 'balance': return [it.a, it.b].join(' | ');
      case 'poll':    return [it.question, (it.options || []).join(' / '), it.answer || ''].join(' | ');
      case 'question':return it.question;
      case 'check':   return it.question;
      case 'truths':  return [...(it.statements || []), it.lie].join(' | ');
      case 'ox':      return [it.statement, it.answer, it.explanation || ''].join(' | ');
      case 'emoji':   return [it.emoji, it.answer, it.hint || ''].join(' | ');
      case 'chosung': return [it.chosung, it.answer, it.hint || ''].join(' | ');
      case 'song':    return [it.title, it.hint || ''].join(' | ');
      case 'liar':    return [it.category, (it.words || []).join(', ')].join(' | ');
      case 'kword':   return [it.answer, it.hint || ''].join(' | ');
      default:        return [it.question, it.answer || ''].join(' | ');
    }
  }).join('\n');
}
